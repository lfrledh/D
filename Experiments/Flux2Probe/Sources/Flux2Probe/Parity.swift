// Numerical checks for the isolated B1 experiment. The denoising schedule,
// evaluated steps and VAE decoding are the same helpers used by Probe.swift.
import CryptoKit
import Flux2
import Foundation
import MLX

private enum FixtureParityError: Error, LocalizedError {
    case invalid(String)
    case mismatch

    var errorDescription: String? {
        switch self {
        case .invalid(let message): message
        case .mismatch: "The staged pipeline did not match the fixed upstream fixture."
        }
    }
}

private struct ParityCheck: Codable {
    let name: String
    let actualShape: [Int]
    let expectedShape: [Int]
    let comparedElements: Int
    let mismatchedElements: Int
    let nonfiniteElements: Int
    let maximumAbsoluteError: Double?
    let absoluteTolerance: Double
    let relativeTolerance: Double
    let passed: Bool
}

private struct ParityReport: Encodable {
    let schemaVersion = 1
    let sourceRevision = "959a4af7c0721c800851c84431ffd3fa1f353f1f"
    let fixtureDirectory: String
    let referenceTest = "Tests/Flux2Tests/Flux2KleinPipelineTests.swift:testTinyKleinPipelineRuns"
    let dtype = "float32"
    let hiddenStateLayers = [0]
    let notes = [
        "Uses the fixed input noise, tokens and mask; no random-noise or tokenizer parity is claimed.",
        "Denoising and decoding use the same shared helpers as the 512px q8 hardware probe.",
        "Tiny float32 parity does not establish q8 model quality, performance or full-model numerical parity.",
        "The upstream fixture was generated by its checked-in Torch/Diffusers reference script; that script was not rerun here.",
        "The upstream static attention-mask cache has no public clear API; residual allocation is reported, not assumed zero.",
    ]
    var fixtureSHA256: [String: String] = [:]
    var status = "running"
    var checks: [ParityCheck] = []
    var error: String?
    var elapsedSeconds = 0.0
    var releasedActiveBytes = 0
    var releasedCacheBytes = 0
    var peakBytes = 0
}

/// Writes a standalone JSON report and throws after saving a numerical failure.
/// The caller maps the thrown error to a nonzero process exit code.
func runFixtureParity(fixtureRoot: URL, reportURL: URL) throws {
    let fm = FileManager.default
    let resolvedFixture = fixtureRoot.resolvingSymlinksInPath().standardizedFileURL
    let resolvedReport = reportURL.deletingLastPathComponent().resolvingSymlinksInPath()
        .appendingPathComponent(reportURL.lastPathComponent).standardizedFileURL
    guard !resolvedReport.path.hasPrefix(resolvedFixture.path + "/"),
          resolvedReport != resolvedFixture,
          (try? fm.attributesOfItem(atPath: reportURL.path)) == nil else {
        throw FixtureParityError.invalid("The fixture report must be a new file outside the fixture directory.")
    }
    let started = ProcessInfo.processInfo.systemUptime
    var report = ParityReport(fixtureDirectory: fixtureRoot.path)
    do {
        report.fixtureSHA256 = try fixtureHashes(root: fixtureRoot)
        report.checks = try autoreleasepool { try evaluateFixture(root: fixtureRoot) }
        report.status = report.checks.allSatisfy(\.passed) ? "passed" : "failed"
        if report.status == "failed" { report.error = FixtureParityError.mismatch.localizedDescription }
    } catch {
        report.status = "failed"
        report.error = error.localizedDescription
    }
    // All model/tensor helper scopes have unwound before taking these counters.
    MLX.Stream.gpu.synchronize()
    MLX.Stream.cpu.synchronize()
    Memory.clearCache()
    report.releasedActiveBytes = Memory.activeMemory
    report.releasedCacheBytes = Memory.cacheMemory
    report.peakBytes = Memory.peakMemory
    report.elapsedSeconds = ProcessInfo.processInfo.systemUptime - started
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
    try encoder.encode(report).write(to: reportURL, options: .atomic)
    let passed = report.checks.filter(\.passed).count
    FileHandle.standardError.write(Data("Fixture parity: \(report.status), \(passed)/\(report.checks.count) comparisons; \(reportURL.path)\n".utf8))
    guard report.status == "passed" else { throw FixtureParityError.mismatch }
}

private func fixtureHashes(root: URL) throws -> [String: String] {
    let paths = [
        "klein_inputs.safetensors", "klein_expected.safetensors",
        "text_encoder/config.json", "text_encoder/model.safetensors",
        "transformer/config.json", "transformer/model.safetensors",
        "vae/config.json", "vae/model.safetensors", "scheduler/config.json",
    ]
    var hashes: [String: String] = [:]
    for path in paths {
        let data = try Data(contentsOf: root.appendingPathComponent(path))
        hashes[path] = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }
    return hashes
}

@inline(never)
private func evaluateFixture(root: URL) throws -> [ParityCheck] {
    let inputs = try MLX.loadArrays(url: root.appendingPathComponent("klein_inputs.safetensors"), stream: .cpu)
    let expected = try MLX.loadArrays(url: root.appendingPathComponent("klein_expected.safetensors"), stream: .cpu)
    func tensor(_ name: String, in values: [String: MLXArray]) throws -> MLXArray {
        guard let value = values[name] else { throw FixtureParityError.invalid("Fixture tensor is missing: \(name)") }
        return value
    }
    func integer(_ name: String) throws -> Int {
        let value = try tensor(name, in: inputs)
        guard value.size == 1 else { throw FixtureParityError.invalid("Expected a scalar fixture value: \(name)") }
        return Int(value.asType(.int32).item(Int32.self))
    }
    let height = try integer("height"), width = try integer("width")
    let steps = try integer("num_inference_steps")
    guard height > 0, width > 0, steps > 0 else { throw FixtureParityError.invalid("Invalid fixture dimensions or step count.") }
    let encoding = try fixtureEncoding(
        root: root,
        inputIds: tensor("input_ids", in: inputs).asType(.int32),
        attentionMask: tensor("attention_mask", in: inputs).asType(.int32)
    )
    let rawLatents = try tensor("latents", in: inputs).asType(.float32)
    let ids = try Flux2PositionIds.prepareLatentIds(rawLatents)
    let packedInput = try Flux2LatentUtils.packLatents(rawLatents)
    MLX.eval(packedInput, ids)
    let packed = try fixtureDenoise(root: root, latents: packedInput, ids: ids, encoding: encoding, steps: steps)
    let decoded = try fixtureDecode(root: root, latents: packed, ids: ids)
    guard decoded.shape == [rawLatents.dim(0), 3, height, width] else {
        throw FixtureParityError.invalid("Unexpected decoded shape: \(decoded.shape)")
    }
    return [
        try compare("prompt_embeds", actual: encoding.promptEmbeds, expected: tensor("prompt_embeds", in: inputs)),
        try compare("text_ids", actual: encoding.textIds, expected: tensor("text_ids", in: inputs), exact: true),
        try compare("latent_ids", actual: ids, expected: tensor("latent_ids", in: inputs), exact: true),
        try compare("packed_latents", actual: packed, expected: tensor("packed_latents", in: expected)),
        try compare("decoded", actual: decoded, expected: tensor("decoded", in: expected)),
    ]
}

@inline(never)
private func fixtureEncoding(root: URL, inputIds: MLXArray, attentionMask: MLXArray) throws -> Flux2PromptEncoding {
    let model = try Flux2Qwen3TextEncoder.load(from: root, dtype: .float32)
    let encoder = Flux2KleinPromptEncoder(textEncoder: model, hiddenStateLayers: [0])
    // encodePrompts in the real probe calls this exact encodeTokens implementation.
    let encoding = try encoder.encodeTokens(inputIds: inputIds, attentionMask: attentionMask)
    MLX.eval(encoding.promptEmbeds, encoding.textIds, encoding.inputIds, encoding.attentionMask)
    return encoding
}

@inline(never)
private func fixtureDenoise(root: URL, latents: MLXArray, ids: MLXArray,
                            encoding: Flux2PromptEncoding, steps: Int) throws -> MLXArray {
    let transformer = try Flux2Transformer2DModel.load(from: root, dtype: .float32)
    let scheduler = try FlowMatchEulerDiscreteScheduler.load(from: root)
    return try probeDenoise(
        transformer: transformer, scheduler: scheduler, latents: latents, ids: ids,
        promptEmbeds: encoding.promptEmbeds, textIds: encoding.textIds, steps: steps
    )
}

@inline(never)
private func fixtureDecode(root: URL, latents: MLXArray, ids: MLXArray) throws -> MLXArray {
    let vae = try Flux2AutoencoderKL.load(from: root, dtype: .float32)
    return try probeDecode(vae: vae, latents: latents, ids: ids)
}

private func compare(_ name: String, actual: MLXArray, expected: MLXArray,
                     exact: Bool = false) -> ParityCheck {
    let atol: Float = exact ? 0 : 1e-4
    let rtol: Float = exact ? 0 : 1e-3
    guard actual.shape == expected.shape else {
        return ParityCheck(name: name, actualShape: actual.shape, expectedShape: expected.shape,
                           comparedElements: 0, mismatchedElements: max(actual.size, expected.size),
                           nonfiniteElements: 0, maximumAbsoluteError: nil,
                           absoluteTolerance: Double(atol), relativeTolerance: Double(rtol), passed: false)
    }
    // Fixture position IDs are small exact integers; float32 represents them exactly.
    let a = actual.asType(.float32).asArray(Float.self)
    let e = expected.asType(.float32).asArray(Float.self)
    var mismatches = 0, nonfinite = 0
    var largest = 0.0
    for (value, reference) in zip(a, e) {
        guard value.isFinite, reference.isFinite else { mismatches += 1; nonfinite += 1; continue }
        let difference = abs(value - reference)
        if difference > atol + rtol * abs(reference) { mismatches += 1 }
        largest = max(largest, abs(Double(value) - Double(reference)))
    }
    return ParityCheck(name: name, actualShape: actual.shape, expectedShape: expected.shape,
                       comparedElements: a.count, mismatchedElements: mismatches,
                       nonfiniteElements: nonfinite, maximumAbsoluteError: largest,
                       absoluteTolerance: Double(atol), relativeTolerance: Double(rtol), passed: mismatches == 0)
}
